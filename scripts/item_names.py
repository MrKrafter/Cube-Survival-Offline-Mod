"""Generate modmenu/src/cube/mod/ItemList.java: every inventory stack the menu can give (the patched references add
an action "cubemod_give_<id>" for each), with its in-game Russian and English name and a group.
Names come from the game's I2 Localization source in the OBB data (term: key, TermType, Description, Languages[16];
language 0 is English, 1 is Russian).
usage: item_names.py"""
import json, os, re, struct, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import refs_codec

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REFS = os.path.join(ROOT, 'textassets', 'r14.bytes')
LOC = os.path.join(ROOT, 'in', 'obb', 'assets', 'bin', 'Data', '209a2243dbc6046478ffa6495f566040')
OUT = os.path.join(ROOT, 'modmenu', 'src', 'cube', 'mod', 'ItemList.java')
# items type -> (group index, ru, en); order is the menu order
GROUPS = {'weapon': (0, 'Оружие и инструменты', 'Weapons and tools'), 'gathering': (0, '', ''),
          'equip': (1, 'Одежда, броня, рюкзаки', 'Clothes, armor, backpacks'),
          'food': (2, 'Еда и медицина', 'Food and medicine'), 'resource': (3, 'Ресурсы и прочее', 'Resources and misc'),
          'furniture': (4, 'Постройки и мебель', 'Buildings and furniture')}
# Items whose game name is a placeholder or shared with others
NAMES = {
    'watch_tower_generator': ('Переносной генератор (для смотровой вышки)', 'Portable generator (for the watch tower)'),
    'buildingsite_watch_tower_generator': ('Генератор (собрать у вышки)', 'Generator (assembled at the tower)'),
    'generator': ('Генератор (старый предмет, не ставится)', 'Generator (old item, cannot be placed)'),
}


def read_str(b, off):
    n = struct.unpack_from('<i', b, off)[0]
    s = b[off + 4:off + 4 + n].decode('utf-8', 'replace')
    return s, off + 4 + ((n + 3) & ~3)


def translations(blob, key):
    k = key.encode()
    for m in re.finditer(re.escape(struct.pack('<i', len(k)) + k), blob):
        off = m.start() + 4 + ((len(k) + 3) & ~3)
        off += 4                      # TermType
        _, off = read_str(blob, off)  # Description
        count = struct.unpack_from('<i', blob, off)[0]
        if count != 16:
            continue
        off += 4
        out = []
        for _ in range(2):
            s, off = read_str(blob, off)
            out.append(s)
        return out
    return None


def java(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ') + '"'


def main():
    R = json.loads(refs_codec.dec(open(REFS, 'rb').read()))
    blob = open(LOC, 'rb').read()
    rows, missing = [], 0
    for sid in R['inventory_stacks']:
        item = R['items'].get(sid)
        if not item:
            continue
        view = R['inventory_stack_view'].get(sid, {})
        tr = translations(blob, view.get('name', '')) if view.get('name') else None
        en, ru = tr if tr else (sid, sid)
        if not tr or not en.strip():
            missing += 1
            en = ru = sid
        if ru.strip() == '':
            ru = en
        ru, en = NAMES.get(sid, (ru, en))
        rows.append((GROUPS[item['type']][0], ru.lower(), sid, ru, en))
    rows.sort()
    lines = ['// Generated by scripts/item_names.py, do not edit.', 'package cube.mod;', '',
             'final class ItemList {',
             '    static final String[][] GROUPS = {']
    seen = {}
    for g, ru, en in sorted({v for v in GROUPS.values() if v[1]}):
        seen[g] = 1
        lines.append('        {%s, %s},' % (java(ru), java(en)))
    lines += ['    };', '    // {group, id, ru, en}', '    static final String[][] ITEMS = {']
    for g, _, sid, ru, en in rows:
        lines.append('        {"%d", %s, %s, %s},' % (g, java(sid), java(ru), java(en)))
    lines += ['    };', '}', '']
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('items:', len(rows), 'without a name:', missing, '->', OUT)


if __name__ == '__main__':
    main()
